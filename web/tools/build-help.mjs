import { readFile, writeFile, mkdir, readdir, unlink } from 'node:fs/promises';
import { createHash } from 'node:crypto';
import { brotliCompressSync, constants as zlibConstants } from 'node:zlib';
import { fileURLToPath } from 'node:url';
import { resolve, join } from 'node:path';
import { validate } from '../local/schema-tools.js';
import { buildHelpPostings } from '../help-search.js';

const root = fileURLToPath(new URL('..', import.meta.url));
const digest = bytes => createHash('sha256').update(bytes).digest('hex');
const approvedSchemaHash = '72a83cfa922f63144142717852b01527eeb5657daf6bb2e6fe9ce98de869d842';
const schemaBytes = await readFile(join(root, 'help/source-contract.schema.json'));
if (digest(schemaBytes) !== approvedSchemaHash) throw new Error('Help authoring contract changed; producer and consumer review is required.');
const sourceBytes = await readFile(join(root, 'help/source-index.json'));
// Help authoring has its own build-time bound; configuration import limits stay unchanged.
if (sourceBytes.length > 1024 * 1024) throw new Error('Help source exceeds the existing 1 MiB source identity limit.');
const source = JSON.parse(new TextDecoder('utf-8', { fatal: true }).decode(sourceBytes));
const findings = validate(source, JSON.parse(schemaBytes));
if (findings.length || source.artifactType !== 'help-index') throw new Error('Unsupported or malformed help source. No partial catalog was built.');
const ids = new Set();
for (const entry of source.entries) {
  if (!/^[a-z][a-z0-9.-]{0,100}$/.test(entry.id) || ids.has(entry.id)) throw new Error('Help topic IDs must be unique public identifiers.');
  ids.add(entry.id);
}
const contentVersion = `sha256:${digest(sourceBytes)}`;
const output = resolve(root, 'help/generated');
await mkdir(output, { recursive: true });
const assets = [];
async function emit(name, value) {
  const bytes = Buffer.from(JSON.stringify(value));
  const sha256 = digest(bytes);
  const path = `/help/generated/${name}-${sha256}.json`;
  await writeFile(join(root, path.slice(1)), bytes);
  await writeFile(join(root, path.slice(1) + '.br'), brotliCompressSync(bytes, { params: { [zlibConstants.BROTLI_PARAM_QUALITY]: 9 } }));
  assets.push(path.slice(1));
  return { path, sha256, bytes: bytes.length };
}
const catalog = [];
for (const entry of source.entries) {
  // Publish only authored product instructions. Internal coverage, owners,
  // qualification paths, binding evidence and user data are never copied.
  const article = await emit(`article-${entry.id}`, { contentVersion, id: entry.id, title: entry.title, bodyMarkdown: entry.bodyMarkdown, capabilityStatus: entry.capabilityStatus, canonicalRefs: entry.canonicalRefs });
  catalog.push({ id: entry.id, title: entry.title, summary: entry.summary, audiences: entry.audiences, article });
}
const catalogAsset = await emit('catalog', { contentVersion, documents: catalog });
const indexAsset = await emit('search', { contentVersion, documentIds: source.entries.map(entry => entry.id), postings: buildHelpPostings(source.entries) });
const manifest = { contractId: 'cq.help.distribution', schemaVersion: 1, contentVersion, authoringSchemaSha256: approvedSchemaHash, catalog: catalogAsset, search: indexAsset };
const manifestBytes = Buffer.from(JSON.stringify(manifest));
await writeFile(join(output, 'manifest.json'), manifestBytes);
// This generated module ships with the executable bundle and is reviewed with
// the source and manifest. It pins static data, not a compromised code bundle.
const release = { manifest: { path: '/help/generated/manifest.json', sha256: digest(manifestBytes), bytes: manifestBytes.length }, contentVersion, sourceSha256: digest(sourceBytes) };
await writeFile(join(root, 'help-release.js'), `// Generated by tools/build-help.mjs; review this pin with the exact help source.\nconst manifest = Object.freeze(${JSON.stringify(release.manifest)});\nexport const helpRelease = Object.freeze({ manifest, contentVersion: ${JSON.stringify(contentVersion)}, sourceSha256: ${JSON.stringify(release.sourceSha256)} });\n`);
assets.push('help/generated/manifest.json');
await writeFile(join(root, 'help/assets.js'), `// Generated by tools/build-help.mjs from the reviewed authoring contract.\nexport const helpAssetPaths = ${JSON.stringify(assets, null, 2)};\n`);
const retained = new Set(assets.flatMap(path => [path.split('/').at(-1), path.split('/').at(-1) + '.br']));
for (const name of await readdir(output)) {
  if (/^(?:catalog|search|article-[a-z][a-z0-9.-]{0,100})-[a-f0-9]{64}\.json(?:\.br)?$/.test(name) && !retained.has(name)) await unlink(join(output, name));
}
console.log(`Built ${catalog.length} public help articles; catalog ${catalogAsset.bytes} bytes, full-text index ${indexAsset.bytes} bytes. Content ${contentVersion}.`);
