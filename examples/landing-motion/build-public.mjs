import { copyFile, mkdir, readFile, rm, stat, writeFile } from 'node:fs/promises';
import { createHash } from 'node:crypto';
import { dirname, extname, relative, resolve } from 'node:path';

process.env.CQ_EXPORT_ROUTE_MAP = '1';
const { assets, canonicalHelpSources, contentTypes, root } = await import('./server.mjs');

const output = resolve(root, '.public-dist');
const local = resolve(root, '.local');
const modulePath = resolve(local, 'worker-routes.mjs');
const manifestPath = resolve(local, 'public-upload-manifest.json');
const expectedRouteCount = 904;
const routes = [...assets.entries()]
  .map(([route, file]) => ({ route, file }))
  .sort((left, right) => left.route.localeCompare(right.route));

if (routes.length !== expectedRouteCount) {
  throw new Error(`Expected ${expectedRouteCount} public routes from the canonical server map, found ${routes.length}`);
}

const isInsideRoot = file => file === root || file.startsWith(`${root}/`);
const resolveSource = file => {
  const canonical = canonicalHelpSources.get(file);
  if (canonical) return canonical;
  const source = resolve(root, file);
  if (!isInsideRoot(source)) throw new Error(`Unsafe public source path: ${file}`);
  return source;
};
const sha256 = buffer => createHash('sha256').update(buffer).digest('hex');
const routeType = file => contentTypes[extname(file)] || 'application/octet-stream';
const compareCodeUnits = (left, right) => left < right ? -1 : left > right ? 1 : 0;
const entriesByFile = new Map();
for (const entry of routes) {
  const source = resolveSource(entry.file);
  if (!entriesByFile.has(entry.file)) entriesByFile.set(entry.file, { source, routes: [] });
  entriesByFile.get(entry.file).routes.push(entry.route);
}

async function copyPublicFiles() {
  await rm(output, { recursive: true, force: true });
  await mkdir(output, { recursive: true });
  for (const [file, entry] of entriesByFile) {
    const destination = resolve(output, file);
    if (!isInsideRoot(destination.replace(output, root))) throw new Error(`Unsafe export path: ${file}`);
    await mkdir(dirname(destination), { recursive: true });
    await copyFile(entry.source, destination);
  }
}

async function manifest() {
  const files = [];
  for (const [file, entry] of entriesByFile) {
    const sourceBytes = await readFile(entry.source);
    const details = await stat(entry.source);
    files.push({
      file,
      bytes: details.size,
      sha256: sha256(sourceBytes),
      mime: routeType(file),
      routes: [...entry.routes].sort(compareCodeUnits),
    });
  }
  return {
    schemaVersion: 1,
    routeCount: routes.length,
    fileCount: files.length,
    routes: routes.map(({ route, file }) => ({ route, file, mime: routeType(file) })),
    files: files.sort((left, right) => left.file.localeCompare(right.file)),
    output: relative(root, output),
  };
}

function renderWorkerRoutes(current) {
  const assetPaths = Object.fromEntries(current.routes.map(({ route, file }) => [route, `/${file}`]));
  const contentTypes = Object.fromEntries(current.routes.map(({ route, mime }) => [route, mime]));
  return `// Generated by build-public.mjs from server.mjs. Do not edit.\nexport const PUBLIC_ROUTES = new Set(${JSON.stringify(Object.keys(assetPaths))});\nexport const PUBLIC_ASSET_PATHS = new Map(${JSON.stringify(Object.entries(assetPaths))});\nexport const PUBLIC_CONTENT_TYPES = new Map(${JSON.stringify(Object.entries(contentTypes))});\n`;
}

async function checkExport(current) {
  for (const file of entriesByFile.keys()) {
    const [source, exported] = await Promise.all([readFile(resolveSource(file)), readFile(resolve(output, file))]);
    if (!source.equals(exported)) throw new Error(`Exported bytes differ for ${file}`);
  }
  const [savedManifest, savedRoutes] = await Promise.all([readFile(manifestPath, 'utf8'), readFile(modulePath, 'utf8')]);
  if (savedManifest !== `${JSON.stringify(current, null, 2)}\n`) throw new Error('Upload manifest is stale');
  if (savedRoutes !== renderWorkerRoutes(current)) throw new Error('Worker route module is stale');
}

const current = await manifest();
if (process.argv.includes('--check')) {
  await checkExport(current);
  process.stdout.write(`Verified ${current.routeCount} routes and ${current.fileCount} unique public files.\n`);
} else {
  await copyPublicFiles();
  await mkdir(local, { recursive: true });
  await writeFile(modulePath, renderWorkerRoutes(current));
  await writeFile(manifestPath, `${JSON.stringify(current, null, 2)}\n`);
  process.stdout.write(`Exported ${current.routeCount} routes and ${current.fileCount} unique public files to ${output}.\n`);
}
